  static String toUpperTr(String input) {
    return input
        .trim()
        .replaceAll('i', 'İ')
        .replaceAll('ı', 'I')
        .replaceAll('ğ', 'Ğ')
        .replaceAll('ü', 'Ü')
        .replaceAll('ş', 'Ş')
        .replaceAll('ö', 'Ö')
        .replaceAll('ç', 'Ç')
        .toUpperCase();
  }

  static String getRegion(String? city) {
    if (city == null || city.trim().isEmpty) return 'Belirtilmemiş';
    final upper = toUpperTr(city);
    return cityToRegion[upper] ?? 'Diğer';
  }

